export function errorMessage(lang: Lang, e: unknown): string {
  const code =
    (e as { code?: string })?.code ??
    ((e as { name?: string })?.name === "QuotaExceededError" ? "QuotaExceededError" : (e as Error)?.message) ??
    "unknown";
  const entry = E[code];
  if (entry) return entry[IDX[lang]];
  return lang === "ar" ? `تعذّر الحفظ (${code}). لم يتغير شيء.` : lang === "fr" ? `Échec (${code}). Rien n’a été modifié.` : `Failed (${code}). Nothing was changed.`;
}

export function amountError(lang: Lang, code: string): string {
  return AMOUNT_E[code]?.[IDX[lang]] ?? code;
}

